const n = (v) => (isNaN(parseFloat(v)) ? 0 : parseFloat(v));
const rm = (v) => `RM ${(isNaN(v) ? 0 : v).toFixed(2)}`;
const uid = () => Math.random().toString(36).slice(2, 10);

function calcProduct(p, a) {
  const unitsPerPlate = n(p.unitsPerPlate);
  if (unitsPerPlate <= 0) return null;
  const printHrsPerPlate = n(p.printHrsPerPlate);
  const filamentGPerPlate = n(p.filamentGPerPlate);
  const postProcessMinPerUnit = n(p.postProcessMinPerUnit);
  const setupMonitorMinPerPlate = n(p.setupMonitorMinPerPlate);

  const filamentGPerUnit = filamentGPerPlate / unitsPerPlate;
  const printHrPerUnit = printHrsPerPlate / unitsPerPlate;
  const filamentCost = (filamentGPerUnit / 1000) * n(a.filamentCostPerKg);
  const electricityCost = ((printHrsPerPlate * n(a.printerPowerW)) / 1000) * n(a.electricityRate) / unitsPerPlate;
  const depreciationCost = ((n(a.printerPrice) / n(a.printerLifetimeHrs)) * printHrsPerPlate) / unitsPerPlate;
  const laborCost = (setupMonitorMinPerPlate / 60) * n(a.laborRate) / unitsPerPlate + (postProcessMinPerUnit / 60) * n(a.laborRate);
  const packagingCost = n(a.packagingCost);
  const totalCost = filamentCost + electricityCost + depreciationCost + laborCost + packagingCost;
  const suggestedPrice = totalCost / (1 - n(a.targetMargin));
  const margin = suggestedPrice - totalCost;
  const wholesalePrice = totalCost / (1 - n(a.wholesaleMargin));
  const wholesaleMarginRM = wholesalePrice - totalCost;
  const shopRetailPrice = wholesalePrice / (1 - n(a.retailMargin));

  return {
    filamentGPerUnit, printHrPerUnit, filamentCost, electricityCost, depreciationCost,
    laborCost, packagingCost, totalCost, suggestedPrice, margin, wholesalePrice,
    wholesaleMarginRM, shopRetailPrice,
  };
}

function nextDocNumber(core, type) {
  const year = new Date().getFullYear();
  const key = `${DOC_PREFIX[type]}-${year}`;
  const next = (core.counters[key] || 0) + 1;
  core.counters[key] = next;
  return `${DOC_PREFIX[type]}-${year}-${String(next).padStart(3, "0")}`;
}
function nextOrderNumber(core) {
  const year = new Date().getFullYear();
  const key = `ORD-${year}`;
  const next = (core.counters[key] || 0) + 1;
  core.counters[key] = next;
  return `ORD-${year}-${String(next).padStart(3, "0")}`;
}

function orderTotal(order) {
  return (order.items || []).reduce((s, it) => s + n(it.qty) * n(it.unitPrice), 0);
}
function orderCOGS(order) {
  return (order.items || []).reduce((s, it) => s + n(it.qty) * n(it.unitCost), 0);
}
function monthKey(dateStr) {
  return (dateStr || "").slice(0, 7) || "unknown";
}
function financeSummary(transactions) {
  const revenue = transactions.filter((t) => t.type === "income").reduce((s, t) => s + n(t.amount), 0);
  const cogs = transactions.filter((t) => t.autoGenerated).reduce((s, t) => s + n(t.cogs), 0);
  const expenses = transactions.filter((t) => t.type === "expense").reduce((s, t) => s + n(t.amount), 0);
  const grossProfit = revenue - cogs;
  const netProfit = grossProfit - expenses;
  return { revenue, cogs, expenses, grossProfit, netProfit };
}
function lowStockMaterials(materials) {
  return (materials || []).filter((m) => n(m.stockGrams) < n(m.reorderThresholdGrams));
}

