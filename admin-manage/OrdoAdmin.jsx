// ---------- inventory ----------
function Inventory({ core, onSave }) {
  const [materials, setMaterials] = useState(core.materials || []);
  const [restockAmount, setRestockAmount] = useState({});

  const update = (id, patch) => setMaterials(materials.map((m) => (m.id === id ? { ...m, ...patch } : m)));
  const add = () => setMaterials([...materials, { id: uid(), name: "New material", costPerKg: 50, stockGrams: 0, reorderThresholdGrams: 500, supplier: "", notes: "" }]);
  const remove = (id) => setMaterials(materials.filter((m) => m.id !== id));
  const restock = (id) => {
    const amt = n(restockAmount[id]);
    if (amt <= 0) return;
    update(id, { stockGrams: n(materials.find((m) => m.id === id).stockGrams) + amt });
    setRestockAmount({ ...restockAmount, [id]: "" });
  };

  const low = lowStockMaterials(materials);

  return (
    <div className="ordo-page">
      <div className="ordo-page-head">
        <h1>Inventory</h1>
        <button className="ordo-btn-primary" onClick={() => onSave(materials)}>Save changes</button>
      </div>

      {low.length > 0 && (
        <div className="ordo-banner">Low stock: {low.map((m) => m.name).join(", ")} — below reorder threshold.</div>
      )}

      <div className="ordo-hint">
        Link materials to products in the Pricing Calculator's "Material" column so stock deducts automatically when an order enters "In Production."
      </div>

      <table className="ordo-table ordo-table-compact" style={{ marginTop: 14 }}>
        <thead><tr><th>Material</th><th>Cost/kg (RM)</th><th>Stock (g)</th><th>Reorder at (g)</th><th>Supplier</th><th>Restock</th><th></th></tr></thead>
        <tbody>
          {materials.map((m) => {
            const isLow = n(m.stockGrams) < n(m.reorderThresholdGrams);
            return (
              <tr key={m.id} style={isLow ? { background: "#F0E2C4" } : undefined}>
                <td><input className="ordo-input" value={m.name} onChange={(e) => update(m.id, { name: e.target.value })} /></td>
                <td><input className="ordo-input" type="number" step="0.01" value={m.costPerKg} onChange={(e) => update(m.id, { costPerKg: e.target.value })} /></td>
                <td className="mono">{n(m.stockGrams).toFixed(0)}</td>
                <td><input className="ordo-input" type="number" value={m.reorderThresholdGrams} onChange={(e) => update(m.id, { reorderThresholdGrams: e.target.value })} /></td>
                <td><input className="ordo-input" value={m.supplier} onChange={(e) => update(m.id, { supplier: e.target.value })} /></td>
                <td>
                  <div style={{ display: "flex", gap: 6 }}>
                    <input className="ordo-input" type="number" placeholder="+g" style={{ width: 70 }} value={restockAmount[m.id] || ""} onChange={(e) => setRestockAmount({ ...restockAmount, [m.id]: e.target.value })} />
                    <button className="ordo-btn-ghost small" onClick={() => restock(m.id)}>Add</button>
                  </div>
                </td>
                <td><button className="ordo-icon-btn" onClick={() => remove(m.id)}>✕</button></td>
              </tr>
            );
          })}
        </tbody>
      </table>
      <button className="ordo-btn-ghost" style={{ marginTop: 10 }} onClick={add}>+ Add material</button>
    </div>
  );
}

