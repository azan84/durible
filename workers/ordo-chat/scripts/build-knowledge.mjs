// Builds src/knowledge.js from the published ordo.earth pages so the chat
// assistant answers from exactly what the site says. Re-run (npm run deploy
// does it) after `node scripts/build-site.mjs` changes the pages.
// The legacy order pages (keychain/bagtag/bizcard/cablewinder.html) are left
// out: the new site no longer links to them and their prices are outdated.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const siteRoot = path.resolve(here, "../../..");
const outFile = path.resolve(here, "../src/knowledge.js");
const SITE = "https://ordo.earth";

const CORE = ["index.html", "solutions.html", "ranges.html", "custom-projects.html", "about.html", "contact.html"];
const listDir = (dir) =>
  fs.readdirSync(path.join(siteRoot, dir)).filter((f) => f.endsWith(".html")).sort().map((f) => `${dir}/${f}`);
const pages = [...CORE, ...listDir("collections"), ...listDir("product")].filter((f) => fs.existsSync(path.join(siteRoot, f)));

const ENTITIES = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " ", ndash: "–", mdash: "—", middot: "·", rsquo: "’", lsquo: "‘", rdquo: "”", ldquo: "“", hellip: "…", times: "×", rarr: "→", larr: "←", bull: "•", copy: "©", deg: "°" };

function decode(s) {
  return s.replace(/&(#x[0-9a-f]+|#\d+|[a-z0-9]+);/gi, (m, e) => {
    if (e[0] === "#") {
      const n = e[1].toLowerCase() === "x" ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10);
      return Number.isFinite(n) ? String.fromCodePoint(n) : m;
    }
    return ENTITIES[e] ?? ENTITIES[e.toLowerCase()] ?? m;
  });
}

// Product and organisation facts also live in JSON-LD.
function extractJsonLd(html) {
  const blocks = [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/gi)];
  const out = blocks.map(([, json]) => {
    try { return JSON.stringify(JSON.parse(json)); } catch { return ""; }
  }).filter(Boolean);
  return out.length ? `\nStructured data on this page (JSON-LD):\n${out.join("\n")}\n` : "";
}

const BOILERPLATE = new Set(["Skip to content", "Leave this empty"]);

function htmlToText(html) {
  let s = html;
  s = s.replace(/<head[\s\S]*?<\/head>/i, "");
  // Header/nav/footer repeat on every page; the contact details are kept from contact.html.
  s = s.replace(/<(script|style|noscript|nav|header|footer|svg|canvas|template)\b[\s\S]*?<\/\1>/gi, " ");
  s = s.replace(/<!--[\s\S]*?-->/g, " ");
  s = s.replace(/<a\b[^>]*href\s*=\s*"([^"]+)"[^>]*>([\s\S]*?)<\/a>/gi, (m, href, inner) => {
    const text = inner.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim();
    if (!text) return " ";
    if (href === "#" || href === "") return ` ${text} `;
    if (/^(#|javascript:)/i.test(href)) return ` ${text} `;
    return ` ${text} [${href}] `;
  });
  s = s.replace(/<img\b[^>]*alt\s*=\s*"([^"]+)"[^>]*>/gi, " (image: $1) ");
  s = s.replace(/<(h[1-6])\b[^>]*>/gi, (m, h) => `\n\n${"#".repeat(Math.min(+h[1] + 1, 6))} `);
  s = s.replace(/<li\b[^>]*>/gi, "\n- ");
  s = s.replace(/<(br|hr)\b[^>]*>/gi, "\n");
  s = s.replace(/<\/?(p|div|section|article|ul|ol|table|tr|blockquote|figure|figcaption|h[1-6]|dl|dt|dd|main|aside|details|summary|form|label)\b[^>]*>/gi, "\n");
  s = s.replace(/<(td|th)\b[^>]*>/gi, " | ");
  s = s.replace(/<[^>]+>/g, " ");
  s = decode(s);
  return s
    .split("\n")
    .map((l) => l.replace(/[ \t ]+/g, " ").trim())
    .filter((l, i, a) => l && l !== "-" && !BOILERPLATE.has(l) && l !== a[i - 1])
    .join("\n")
    .replace(/\n(#+ )/g, "\n\n$1")
    .trim();
}

const sections = pages.map((file) => {
  const html = fs.readFileSync(path.join(siteRoot, file), "utf8");
  const title = decode((html.match(/<title>([\s\S]*?)<\/title>/i)?.[1] ?? file).trim());
  // The site is served with clean URLs (/contact, /product/nfc-keychain).
  const clean = file === "index.html" ? "/" : `/${file.replace(/\.html$/, "")}`;
  const jsonld = file === "index.html" || file.startsWith("product/") ? extractJsonLd(html) : "";
  return `=== PAGE: ${title}\nURL: ${SITE}${clean} (link: ${clean})\n\n${htmlToText(html)}\n${jsonld}`;
});

const knowledge = sections.join("\n\n");
fs.writeFileSync(
  outFile,
  `// Generated by scripts/build-knowledge.mjs — do not edit by hand.\nexport default ${JSON.stringify(knowledge)};\n`,
);
console.log(`knowledge.js: ${pages.length} pages, ${knowledge.length.toLocaleString()} chars (~${Math.round(knowledge.length / 4).toLocaleString()} tokens)`);
